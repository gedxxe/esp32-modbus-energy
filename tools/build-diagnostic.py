"""Maintain the legacy include path while checking the shared Fort library."""
from pathlib import Path
import subprocess,sys
root=Path(__file__).resolve().parent.parent
subprocess.run([sys.executable,str(root/'tools/check_meter.py')],check=True)
path=root/'firmware/include/diagnostic_engine.h'
content='// Compatibility header generated by tools/build-diagnostic.py.\n#pragma once\n#include <FortDiagnostics.h>\n'
if '--check' in sys.argv:
 if path.read_text(encoding='utf-8')!=content:raise SystemExit('Stale compatibility header: run python tools/build-diagnostic.py')
else:path.write_text(content,encoding='utf-8',newline='\n')
print('PASS: diagnostic compatibility include uses the shared FortMeter library')
