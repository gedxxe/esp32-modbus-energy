"""Generate and verify the lossless, flash-resident OLED frame pack (stdlib only)."""
from pathlib import Path
import hashlib,json,sys
root=Path(__file__).resolve().parent.parent
folder=root/'firmware/assets/oled'
meta=json.loads((folder/'idle.json').read_text(encoding='utf-8'))
assert meta['width']==128 and meta['height']==64 and meta['frame_bytes']==1024 and 0<meta['frames']<=65535 and 0<meta['period_ms']<=1000
packed=(folder/'idle.rle').read_bytes();offsets=meta['offsets']
assert hashlib.sha256(packed).hexdigest()==meta['packed_sha256']
assert len(offsets)==meta['frames']+1 and offsets[0]==0 and offsets[-1]==len(packed)
raw=bytearray()
for a,b in zip(offsets,offsets[1:]):
 assert 0<=a<b<=len(packed)
 source=packed[a:b];frame=bytearray();i=0
 while i<len(source):
  token=source[i];i+=1
  if token<128:
   n=token+1;assert i+n<=len(source);frame.extend(source[i:i+n]);i+=n
  else:
   assert i<len(source);frame.extend([source[i]]*(token-127));i+=1
 assert len(frame)==meta['frame_bytes'];raw.extend(frame)
assert hashlib.sha256(raw).hexdigest()==meta['raw_sha256']
header=f"""// Generated by tools/build-oled.py. Original artwork supplied by the project author.
#pragma once
#include <stdint.h>
namespace fort {{
constexpr uint16_t OLED_FRAME_WIDTH={meta['width']},OLED_FRAME_HEIGHT={meta['height']},OLED_FRAME_COUNT={meta['frames']};
constexpr uint32_t OLED_FRAME_PERIOD_MS={meta['period_ms']};
bool loadOLEDFrame(uint16_t frame,uint8_t *destination);
}} // namespace fort
"""
rows=['  '+','.join('0x%02x'%x for x in packed[i:i+24])+',' for i in range(0,len(packed),24)]
source="""// Generated by tools/build-oled.py. Artwork supplied by the project author, see NOTICE.
#include "oled_frames.h"
#include "screen_saver.h"
#ifdef ARDUINO
#include <Arduino.h>
#else
#define PROGMEM
#endif
namespace fort {
static const uint8_t FRAME_PACKETS[] PROGMEM = {
"""+'\n'.join(rows)+'\n};\nstatic const uint32_t FRAME_OFFSETS[] PROGMEM = {\n'+','.join(str(x) for x in offsets)+"""
};
bool loadOLEDFrame(uint16_t frame,uint8_t *destination){
  if(frame>=OLED_FRAME_COUNT)return false;
  uint32_t a=FRAME_OFFSETS[frame],b=FRAME_OFFSETS[frame+1];
  return decodeOLEDRun(FRAME_PACKETS+a,b-a,destination,1024);
}
} // namespace fort
"""
for path,text in [(root/'firmware/include/oled_frames.h',header),(root/'firmware/src/oled_frames.cpp',source)]:
 if '--check' in sys.argv:
  if not path.exists() or path.read_text(encoding='utf-8')!=text:raise SystemExit('Stale OLED frame source. Run python tools/build-oled.py')
 else:path.write_text(text,encoding='utf-8',newline='\n')
print(f"PASS: {meta['frames']} OLED frames, {len(raw):,} original bytes verified, {len(packed):,} compressed bytes")
