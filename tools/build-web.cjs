// Compile browser code; embed compressed assets without requiring Node on the ESP32.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const zlib = require("node:zlib");
const esbuild = require("esbuild");
const root = path.resolve(__dirname, "..");
const check = process.argv.includes("--check");
const requiredNode = JSON.parse(
  fs.readFileSync(path.join(root, "package.json")),
).engines.node;
if (process.versions.node !== requiredNode)
  throw new Error(
    `Use Node ${requiredNode} for reproducible web assets (current: ${process.versions.node}).`,
  );
const source = (file) => fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
const digest = (data) => crypto.createHash("sha256").update(data).digest("hex");
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const target = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(target) : [target];
  });
}
function install(file, content) {
  if (check) {
    if (
      !fs.existsSync(file) ||
      !fs.readFileSync(file).equals(Buffer.from(content))
    ) {
      throw new Error(
        `Stale generated file: ${path.relative(root, file)}. Run npm run build:web.`,
      );
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
(async () => {
  const build = await esbuild.build({
    entryPoints: [path.join(root, "web/app.jsx")],
    outfile: "app.js",
    bundle: true,
    minify: true,
    write: false,
    format: "iife",
    target: ["es2020"],
    jsx: "automatic",
    define: { "process.env.NODE_ENV": '"production"' },
    legalComments: "inline",
    sourcemap: false,
    charset: "utf8",
  });
  const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json")));
  const parts = [
    [
      "index",
      "/",
      "text/html; charset=utf-8",
      Buffer.from(source(path.join(root, "web/index.html"))),
    ],
    [
      "app",
      "/assets/app.js",
      "application/javascript; charset=utf-8",
      build.outputFiles.find((file) => file.path.endsWith(".js")).contents,
    ],
    [
      "style",
      "/assets/app.css",
      "text/css; charset=utf-8",
      build.outputFiles.find((file) => file.path.endsWith(".css")).contents,
    ],
  ];
  const notices = [
    "THIRD-PARTY NOTICES\nOriginal project code: GPL-3.0-only. Dependencies retain their own terms.\n",
  ];
  for (const [label, file] of [
    ["React Bits (David Haz)", "web/vendor/react-bits/LICENSE.md"],
    ["React", "node_modules/react/LICENSE"],
    ["React DOM", "node_modules/react-dom/LICENSE"],
    ["Scheduler", "node_modules/scheduler/LICENSE"],
    ["Motion", "node_modules/motion/LICENSE.md"],
    ["Framer Motion", "node_modules/framer-motion/LICENSE.md"],
    ["Motion DOM", "node_modules/motion-dom/LICENSE.md"],
    ["Motion Utils", "node_modules/motion-utils/LICENSE.md"],
    ["GSAP", "web/vendor/gsap-NOTICE.txt"],
  ])
    notices.push(`\n--- ${label} ---\n${source(path.join(root, file))}`);
  parts.push([
    "notices",
    "/assets/third-party.txt",
    "text/plain; charset=utf-8",
    Buffer.from(notices.join("\n")),
  ]);
  let header =
    "// Generated by tools/build-web.cjs. Edit web/ sources, then npm run build:web.\n#pragma once\n#include <Arduino.h>\n";
  const assets = {};
  let compressedTotal = 0;
  for (const [name, url, mime, raw] of parts) {
    const gzip = zlib.gzipSync(raw, { level: 9 });
    gzip[9] = 255; // Keep generated bytes identical across Windows and Linux.
    compressedTotal += gzip.length;
    const symbol = `WEB_${name.toUpperCase()}_GZIP`;
    const rows = [];
    for (let i = 0; i < gzip.length; i += 20)
      rows.push(
        "  " +
          [...gzip.subarray(i, i + 20)]
            .map((byte) => "0x" + byte.toString(16).padStart(2, "0"))
            .join(",") +
          ",",
      );
    header += `const uint8_t ${symbol}[] PROGMEM = {\n${rows.join("\n")}\n};\nconstexpr size_t ${symbol}_LEN = ${gzip.length};\n`;
    assets[url] = {
      symbol,
      mime,
      raw: raw.length,
      gzip: gzip.length,
      sha256: digest(gzip),
    };
    if (!check) install(path.join(root, "output/web", name + ".gz"), gzip);
  }
  if (compressedTotal > 160 * 1024)
    throw new Error(
      `Web assets exceed the 160 KiB compressed budget: ${compressedTotal}`,
    );
  const inputs = [
    ...walk(path.join(root, "web")).filter(
      (file) => path.basename(file) !== "bundle.json",
    ),
    ...["tools/build-web.cjs", "package.json", "package-lock.json"].map(
      (file) => path.join(root, file),
    ),
  ].sort();
  const manifest = {
    version: pkg.version,
    transport: "gzip",
    compressed_total: compressedTotal,
    libraries: { ...pkg.dependencies, esbuild: pkg.devDependencies.esbuild },
    assets,
    inputs: Object.fromEntries(
      inputs.map((file) => [
        path.relative(root, file).replaceAll("\\", "/"),
        digest(source(file)),
      ]),
    ),
    header_sha256: digest(header),
  };
  install(path.join(root, "firmware/include/web_ui.h"), header);
  install(
    path.join(root, "web/bundle.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );
  console.log(
    `PASS: offline React/React Bits bundle, ${compressedTotal.toLocaleString("en-US")} bytes gzip / 160 KiB budget`,
  );
})().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
